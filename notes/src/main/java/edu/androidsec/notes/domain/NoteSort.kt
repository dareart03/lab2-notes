package edu.androidsec.notes.domain

/**
 * Варианты сортировки результатов поиска. Это закрытый список: каждому значению в [edu.androidsec.notes.data.db.NoteDao]
 * соответствует свой готовый запрос, поэтому подставить в SQL имя колонки из строки невозможно.
 */
enum class NoteSort {
    /** По заголовку, А→Я без учёта регистра (для латиницы). */
    TITLE,

    /** По дате изменения: сначала новые. */
    NEWEST,

    /** По дате изменения: сначала старые. */
    OLDEST,
}
