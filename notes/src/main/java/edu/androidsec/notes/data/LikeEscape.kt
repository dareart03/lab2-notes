package edu.androidsec.notes.data

/**
 * Экранирует спецсимволы `LIKE`, чтобы `%`, `_` и `\` в строке поиска искались буквально.
 * Используется вместе с `ESCAPE '\'` в запросах DAO.
 *
 * Обратный слэш заменяется первым: иначе слэши, добавленные для `%` и `_`, задвоились бы.
 */
fun String.escapeForLike(): String =
    replace("\\", "\\\\")
        .replace("%", "\\%")
        .replace("_", "\\_")
